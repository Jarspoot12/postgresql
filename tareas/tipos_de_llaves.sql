-- candidate key: atributo o conjunto de ellos que identifican de forma única, menos la llave primaria

-- super key: conjunto de atributos que puede identificar de forma única, es un super conjunto de una clave candidata

-- foreign key: llaves usadas para apuntar a la llave primaria de otra tabla, deben ser campos de iguales tipos y longitudes en ambas tablas relacionadas

-- composite key: cuando una clave primaria consta de más de un atributo

-- las llaves, intrucciones de nulos, tipos de datos, son CONSTRAINTS (restricciones), que buscan reducir basura que entra
